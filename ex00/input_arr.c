#include "rush01.h"

int	input_arr(char **argv, int input[16])
{
	int	i;

	i = 0;
	while (i < 16 && argv[1][i * 2])
	{
		input[i] = argv[1][i * 2] - '0';
		i++;
	}
	return (TRUE);
}
